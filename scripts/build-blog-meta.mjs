// Generates src/data/blog-meta.ts — a lightweight metadata-only mirror of
// src/data/blog.ts (no article bodies / FAQs). Listing pages import this so
// they never pull the ~470KB full article corpus into the initial bundle.
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const root = process.cwd();
const { blogPosts } = await import(pathToFileURL(path.join(root, "src/data/blog.ts")).href);

const meta = blogPosts.map((p) => ({
  slug: p.slug,
  title: p.title,
  description: p.description,
  excerpt: p.excerpt,
  author: p.author,
  datePublished: p.datePublished,
  readTime: p.readTime,
  category: p.category,
  tags: p.tags,
  recommendedProvider: p.recommendedProvider,
  featured: p.featured,
}));

const out = `// AUTO-GENERATED by scripts/build-blog-meta.mjs — do not edit by hand.
// Source of truth: src/data/blog.ts. Regenerate with: npx tsx scripts/build-blog-meta.mjs

export interface BlogPostMeta {
  slug: string;
  title: string;
  description: string;
  excerpt: string;
  author: string;
  datePublished: string;
  readTime: string;
  category: string;
  tags: string[];
  recommendedProvider?: string;
  featured?: boolean;
}

export const blogPostsMeta: BlogPostMeta[] = ${JSON.stringify(meta, null, 2)};
`;

writeFileSync(path.join(root, "src/data/blog-meta.ts"), out);
console.log(`blog-meta.ts written (${meta.length} posts)`);
